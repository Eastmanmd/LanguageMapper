import { useEffect, useMemo, useState } from 'react'
import { useNavigate } from 'react-router-dom'
import AfricaDotMap from '../AfricaDotMap'
import CountUp from '../CountUp'
import LanguageSearch from '../LanguageSearch'
import { NigeriaFlagIcon } from '../icons'
import stats from '../../data/africaStats.json'
import { loadAtlas, loadBorders } from '../../utils/loadAtlas'
import { CATEGORICAL } from '../../utils/atlasColors'
import { countryName } from '../../utils/countries'
import { useTheme } from '../../context/ThemeContext'

const fmt = (n) => n.toLocaleString('en-US')
const pct = (n, total) => Math.round((n / total) * 100)

// Well-known languages to try from the hero, each with a word list so the
// atlas can show its relatives straight away.
const QUICK_PICKS = [
  { g: 'swah1253', name: 'Swahili' },
  { g: 'haus1257', name: 'Hausa' },
  { g: 'yoru1245', name: 'Yoruba' },
  { g: 'amha1245', name: 'Amharic' },
  { g: 'zulu1248', name: 'Zulu' },
  { g: 'nucl1347', name: 'Wolof' },
  { g: 'ling1263', name: 'Lingala' },
]

// Generated by `npm run build-africa-data`, so they track the atlas data.
const STAT_COLORS = [
  'text-naija-600 dark:text-naija-400',
  'text-adire-600 dark:text-adire-400',
  'text-ankara-600 dark:text-ankara-400',
]
const STATS = [
  { value: stats.languages, label: 'Languages mapped' },
  {
    value: stats.families,
    label: `Language families, the largest being ${stats.largestFamily.name} with ${fmt(stats.largestFamily.count)} languages`,
  },
  { value: stats.isolateCount, label: 'Isolates: languages with no known relatives' },
  { value: stats.countries, label: 'Countries' },
  { value: stats.endangered, label: 'Endangered, with fewer and fewer young speakers' },
  { value: stats.wordLists, label: 'With basic word lists you can compare' },
].map((stat, i) => ({ ...stat, color: STAT_COLORS[i % STAT_COLORS.length] }))

// Lightest to darkest: the further along Glottolog's scale, the darker the segment.
const ENDANGERED_SHADES = ['bg-ankara-300', 'bg-ankara-400', 'bg-ankara-600', 'bg-ankara-800']

const ENDANGERMENT_LABELS = [
  'Not endangered',
  'Threatened',
  'Shifting: fewer children are learning it',
  'Moribund: spoken mostly by older people',
  'Nearly extinct',
  'Extinct',
]

export default function Home() {
  const navigate = useNavigate()
  const { dark } = useTheme()
  const theme = dark ? 'dark' : 'light'
  const [atlas, setAtlas] = useState(null)
  const [borders, setBorders] = useState(null)
  // A family chip being hovered, or one clicked to keep it highlighted.
  const [hoveredGroup, setHoveredGroup] = useState(null)
  const [pinnedGroup, setPinnedGroup] = useState(null)
  const [spotlight, setSpotlight] = useState(null)

  useEffect(() => {
    loadAtlas().then(setAtlas).catch(() => {})
    loadBorders().then(setBorders).catch(() => {})
  }, [])

  const languageOptions = useMemo(
    () =>
      (atlas?.languages ?? [])
        .map((l) => ({ id: l.g, name: l.n }))
        .sort((a, b) => a.name.localeCompare(b.name)),
    [atlas],
  )

  const openLanguage = (g) => navigate(`/atlas?lang=${g}`)

  const surpriseMe = () => {
    // Languages with a word list, so the atlas can show their relatives too.
    const pool = atlas.languages.filter((l) => l.w && l.g !== spotlight)
    setSpotlight(pool[Math.floor(Math.random() * pool.length)].g)
  }

  const groups = atlas ? atlas.tree.branches(null) : []
  const spot = spotlight && atlas ? atlas.tree.byId.get(spotlight) : null
  const spotLineage = spot ? atlas.tree.displayLineage(spot) : []

  return (
    <div className="flex-1 overflow-y-auto bg-white transition-colors dark:bg-[#0a0a0a]">
      <section className="relative overflow-hidden px-6 pt-8 pb-12 md:px-10 md:pt-12 md:pb-16">
        <div className="pointer-events-none absolute -top-32 -right-24 h-96 w-96 rounded-full bg-gradient-to-br from-naija-400/25 via-adire-400/20 to-ankara-400/15 blur-3xl" />
        <div className="pointer-events-none absolute -bottom-40 -left-32 h-96 w-96 rounded-full bg-gradient-to-tr from-adire-400/15 to-naija-400/20 blur-3xl" />
        {/* Adire cloth behind the hero, faded out toward the text so it reads as
            texture rather than pattern. */}
        <div
          className="fabric-adire pointer-events-none absolute inset-0"
          style={{
            maskImage: 'radial-gradient(70% 65% at 92% 8%, #000 0%, transparent 70%)',
            WebkitMaskImage: 'radial-gradient(70% 65% at 92% 8%, #000 0%, transparent 70%)',
          }}
        />

        <div className="relative flex flex-col gap-10 md:flex-row md:items-center">
          <div className="animate-rise-in md:flex-1">
            <span className="inline-flex items-center gap-2 rounded-full border border-gray-200 bg-white/70 px-3 py-1 text-xs font-medium text-gray-600 dark:border-white/15 dark:bg-white/5 dark:text-gray-300">
              <span aria-hidden="true">🌍</span>
              {fmt(stats.languages)} languages · {stats.families} families · {stats.isolateCount} isolates
            </span>
            <h1 className="mt-5 max-w-xl text-4xl font-medium leading-[1.1] tracking-tight text-gray-900 md:text-5xl dark:text-white">
              Every language in Africa,{' '}
              <span className="bg-gradient-to-r from-naija-600 to-adire-600 bg-clip-text text-transparent dark:from-naija-400 dark:to-adire-400">
                on one map
              </span>
              .
            </h1>
            <p className="mt-5 max-w-lg text-lg leading-relaxed text-gray-600 dark:text-gray-400">
              Search a language to see where it&rsquo;s spoken, which family it belongs to, and which
              other languages share its basic words.
            </p>

            <div className="mt-6 max-w-md">
              {/* Keyed on load so the box is usable as soon as the names arrive. */}
              <LanguageSearch
                key={atlas ? 'ready' : 'loading'}
                languageOptions={languageOptions}
                selectedLanguage={null}
                onSelect={openLanguage}
                onClear={() => {}}
                placeholder={`Search ${fmt(stats.languages)} languages…`}
              />
              <div className="mt-3 flex flex-wrap items-center gap-1.5">
                <span className="mr-1 text-xs text-gray-500 dark:text-gray-400">Try</span>
                <button
                  onClick={surpriseMe}
                  disabled={!atlas}
                  className="inline-flex items-center gap-1 rounded-full border border-adire-200 bg-adire-50 px-2.5 py-1 text-xs font-medium text-adire-700 transition-colors hover:bg-adire-100 disabled:opacity-50 dark:border-adire-400/30 dark:bg-adire-500/10 dark:text-adire-300 dark:hover:bg-adire-500/20"
                >
                  <span aria-hidden="true">🎲</span> Surprise me
                </button>
                {QUICK_PICKS.map((pick) => (
                  <button
                    key={pick.g}
                    onClick={() => openLanguage(pick.g)}
                    className="rounded-full border border-gray-200 bg-white/70 px-2.5 py-1 text-xs font-medium text-gray-700 transition-colors hover:border-naija-300 hover:bg-naija-50 hover:text-naija-700 dark:border-white/15 dark:bg-white/5 dark:text-gray-300 dark:hover:border-naija-400/40 dark:hover:bg-naija-500/10 dark:hover:text-naija-300"
                  >
                    {pick.name}
                  </button>
                ))}
              </div>
            </div>

            <div className="mt-8 flex flex-wrap gap-3">
              <button
                onClick={() => navigate('/atlas')}
                className="rounded-full bg-gradient-to-r from-naija-600 to-adire-600 px-6 py-3 text-sm font-medium text-white shadow-md shadow-naija-600/20 transition-transform hover:scale-[1.03] dark:from-naija-500 dark:to-adire-500"
              >
                Explore the atlas
              </button>
              <button
                onClick={() => navigate('/map')}
                className="rounded-full border border-gray-200 px-6 py-3 text-sm font-medium text-gray-700 transition-colors hover:border-gray-300 hover:bg-gray-50 dark:border-white/15 dark:text-gray-200 dark:hover:border-white/30 dark:hover:bg-white/5"
              >
                See Nigeria in depth
              </button>
            </div>
          </div>

          <figure className="animate-rise-in md:flex-1" style={{ animationDelay: '0.15s' }}>
            <div className="rounded-2xl border border-gray-200 bg-white/80 p-4 shadow-lg shadow-naija-600/5 backdrop-blur dark:border-white/10 dark:bg-white/5">
              <AfricaDotMap
                atlas={atlas}
                borders={borders}
                theme={theme}
                onSelect={openLanguage}
                highlight={hoveredGroup ?? pinnedGroup}
                spotlight={spotlight}
              />
              <div className="mt-3 flex flex-wrap gap-1.5" onMouseLeave={() => setHoveredGroup(null)}>
                {groups.map((group, i) => {
                  const active = (hoveredGroup ?? pinnedGroup) === group.id
                  return (
                    <button
                      key={group.id}
                      onMouseEnter={() => setHoveredGroup(group.id)}
                      onFocus={() => setHoveredGroup(group.id)}
                      onBlur={() => setHoveredGroup(null)}
                      onClick={() => setPinnedGroup((p) => (p === group.id ? null : group.id))}
                      aria-pressed={pinnedGroup === group.id}
                      className={`flex items-center gap-1.5 rounded-full border px-2 py-0.5 text-xs transition-colors ${
                        active
                          ? 'border-gray-400 bg-gray-100 text-gray-900 dark:border-white/40 dark:bg-white/10 dark:text-white'
                          : 'border-gray-200 text-gray-600 hover:border-gray-300 dark:border-white/15 dark:text-gray-300'
                      }`}
                    >
                      <span className="h-2 w-2 rounded-full" style={{ backgroundColor: CATEGORICAL[theme][i] }} />
                      {group.name}
                      <span className="tabular-nums text-gray-400 dark:text-gray-500">{fmt(group.count)}</span>
                    </button>
                  )
                })}
              </div>
            </div>
            {spot ? (
              <div className="mt-3 rounded-xl border border-gray-200 bg-white p-4 text-sm dark:border-white/10 dark:bg-white/5" aria-live="polite">
                <div className="flex items-start justify-between gap-3">
                  <div className="min-w-0">
                    <p className="text-base font-medium text-gray-900 dark:text-white">{spot.n}</p>
                    <p className="text-gray-500 dark:text-gray-400">
                      {spot.c.length > 0 ? `Spoken in ${spot.c.map(countryName).join(', ')}` : 'Location not recorded'}
                    </p>
                    <p className="mt-1 truncate text-xs text-gray-400 dark:text-gray-500">
                      {spotLineage.slice(0, 3).map((id) => atlas.tree.name(id)).join(' › ')}
                      {spotLineage.length > 3 && ' › …'}
                    </p>
                    {ENDANGERMENT_LABELS[spot.e] && (
                      <p className="mt-1 text-xs text-gray-500 dark:text-gray-400">{ENDANGERMENT_LABELS[spot.e]}</p>
                    )}
                  </div>
                  <button
                    onClick={() => setSpotlight(null)}
                    aria-label="Close"
                    className="text-gray-400 hover:text-gray-700 dark:hover:text-white"
                  >
                    ×
                  </button>
                </div>
                <div className="mt-3 flex flex-wrap gap-2 text-xs font-medium">
                  <button
                    onClick={() => navigate(`/atlas?lang=${spot.g}&color=similar`)}
                    className="rounded-full bg-naija-600 px-3 py-1.5 text-white hover:bg-naija-700"
                  >
                    See its relatives &rarr;
                  </button>
                  <button
                    onClick={surpriseMe}
                    className="rounded-full border border-gray-200 px-3 py-1.5 text-gray-700 hover:bg-gray-50 dark:border-white/15 dark:text-gray-200 dark:hover:bg-white/5"
                  >
                    <span aria-hidden="true">🎲</span> Another one
                  </button>
                </div>
              </div>
            ) : (
              <figcaption className="mt-3 text-xs text-gray-400 dark:text-gray-500">
                Every dot is a language. Hover one for details, click to open it, or highlight a family
                above.
              </figcaption>
            )}
          </figure>
        </div>
      </section>

      <div className="border-t border-gray-200 px-6 md:px-10 dark:border-white/10">
        <div className="grid grid-cols-2 gap-x-6 gap-y-8 py-10 sm:grid-cols-3 lg:grid-cols-6">
          {STATS.map((stat) => (
            <div key={stat.label}>
              <div className={`text-3xl font-semibold tracking-tight ${stat.color}`}>
                <CountUp value={stat.value} />
              </div>
              <div className="mt-1 text-sm text-gray-500 dark:text-gray-400">
                {stat.label}
              </div>
            </div>
          ))}
        </div>
      </div>

      <section className="border-t border-gray-200 px-6 py-16 md:px-10 md:py-20 dark:border-white/10">
        <h2 className="text-2xl font-medium tracking-tight text-gray-900 md:text-3xl dark:text-white">
          How Africa&rsquo;s languages fit together
        </h2>
        <p className="mt-3 max-w-2xl text-base leading-relaxed text-gray-600 dark:text-gray-400">
          Nearly a third of the world&rsquo;s languages are spoken in Africa. Most belong to one of four
          big groups, a few stand entirely alone, and many are at risk.
        </p>

        <div className="mt-8">
          <div className="flex h-4 gap-0.5 overflow-hidden rounded-full">
            {stats.groups.map((group, i) => (
              <button
                key={group.id}
                onClick={() => navigate(`/atlas?focus=${group.id}`)}
                title={`${group.name}: ${fmt(group.count)} languages. Open in the atlas`}
                aria-label={`Open ${group.name} in the atlas`}
                className="transition-opacity hover:opacity-80"
                style={{ flexGrow: group.count, backgroundColor: CATEGORICAL[theme][i] }}
              />
            ))}
          </div>
          <ul className="mt-3 flex flex-wrap gap-x-5 gap-y-2 text-sm text-gray-600 dark:text-gray-400">
            {stats.groups.map((group, i) => (
              <li key={group.id}>
                <button
                  onClick={() => navigate(`/atlas?focus=${group.id}`)}
                  className="group flex items-center gap-2"
                >
                  <span className="h-2.5 w-2.5 rounded-full" style={{ backgroundColor: CATEGORICAL[theme][i] }} />
                  <span className="font-medium text-gray-900 group-hover:underline dark:text-white">{group.name}</span>
                  {pct(group.count, stats.languages)}% · {fmt(group.count)}
                </button>
              </li>
            ))}
          </ul>
          <p className="mt-2 text-xs text-gray-400 dark:text-gray-500">
            The four traditional groupings. Linguists accept Afro-Asiatic as one family; the other three
            bring together families whose relationship hasn&rsquo;t been proven. Click a group to explore
            its branches.
          </p>
        </div>

        <div className="mt-8 grid gap-4 sm:grid-cols-2">
          <div className="rounded-2xl border border-gray-200 p-6 dark:border-white/10 dark:bg-white/5">
            <p className="text-sm text-gray-500 dark:text-gray-400">Alone in the world</p>
            <p className="mt-1 text-3xl font-semibold tracking-tight text-adire-600 dark:text-adire-400">
              {stats.isolateCount} isolates
            </p>
            <p className="mt-2 text-sm leading-relaxed text-gray-600 dark:text-gray-400">
              Languages with no known relatives anywhere. Pick one to see where it&rsquo;s spoken:
            </p>
            <div className="mt-3 flex flex-wrap gap-1.5">
              {stats.isolates.map((isolate) => (
                <button
                  key={isolate.g}
                  onClick={() => openLanguage(isolate.g)}
                  className="rounded-full border border-adire-200 px-2.5 py-1 text-xs font-medium text-adire-700 transition-colors hover:bg-adire-50 dark:border-adire-400/30 dark:text-adire-300 dark:hover:bg-adire-500/10"
                >
                  {isolate.name}
                </button>
              ))}
            </div>
          </div>
          <div className="rounded-2xl border border-gray-200 p-6 dark:border-white/10 dark:bg-white/5">
            <p className="text-sm text-gray-500 dark:text-gray-400">At risk</p>
            <p className="mt-1 text-3xl font-semibold tracking-tight text-ankara-600 dark:text-ankara-400">
              {fmt(stats.endangered)} endangered
            </p>
            <div
              className="mt-3 flex h-2.5 gap-0.5 overflow-hidden rounded-full bg-gray-100 dark:bg-white/10"
              role="img"
              aria-label={`${pct(stats.endangered, stats.languages)}% of languages are endangered`}
            >
              {stats.endangeredLevels.map((level, i) => (
                <span
                  key={level.label}
                  title={`${level.label}: ${fmt(level.count)}`}
                  className={ENDANGERED_SHADES[i]}
                  style={{ width: `${(level.count / stats.languages) * 100}%` }}
                />
              ))}
            </div>
            <ul className="mt-2 grid grid-cols-2 gap-x-4 gap-y-1 text-xs text-gray-500 dark:text-gray-400">
              {stats.endangeredLevels.map((level, i) => (
                <li key={level.label} className="flex items-center gap-1.5">
                  <span className={`h-2 w-2 rounded-full ${ENDANGERED_SHADES[i]}`} />
                  {level.label}
                  <span className="ml-auto tabular-nums">{fmt(level.count)}</span>
                </li>
              ))}
            </ul>
            <p className="mt-2 text-sm leading-relaxed text-gray-600 dark:text-gray-400">
              {pct(stats.endangered, stats.languages)}% of Africa&rsquo;s languages, with fewer children
              learning them each generation. Another {stats.extinct} are no longer spoken.
            </p>
          </div>
        </div>

        <div className="relative mt-8 overflow-hidden rounded-3xl bg-gradient-to-br from-naija-50 via-white to-adire-50 p-8 md:p-10 dark:from-naija-500/10 dark:via-transparent dark:to-adire-500/10">
          <div
            className="fabric-ankara pointer-events-none absolute inset-0"
            style={{
              maskImage: 'linear-gradient(255deg, #000 0%, transparent 45%)',
              WebkitMaskImage: 'linear-gradient(255deg, #000 0%, transparent 45%)',
            }}
          />
          <div className="relative flex max-w-2xl items-start gap-3">
            <NigeriaFlagIcon className="mt-1.5 h-4 w-6 shrink-0 rounded-sm shadow-sm" />
            <div>
              <p className="text-base leading-relaxed text-gray-700 dark:text-gray-300">
                We go deepest on {countryName(stats.topCountry.code)}, home to{' '}
                {fmt(stats.topCountry.count)} languages, more than any other African country, with
                state-by-state maps and hand-written profiles.
              </p>
              <button
                onClick={() => navigate('/map')}
                className="mt-4 text-sm font-medium text-naija-600 hover:underline dark:text-naija-400"
              >
                See Nigeria in depth &rarr;
              </button>
            </div>
          </div>
        </div>
      </section>
    </div>
  )
}
